#!/usr/bin/env node
// Sync .antigravityignore to other ignore files safely.

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

export const DEFAULT_SOURCE = '.antigravityignore';
export const DEFAULT_TARGETS = Object.freeze(['.geminiignore', '.aiexclude']);

const keyOf = (p) => (process.platform === 'win32' ? p.toLowerCase() : p);
const lf = (s) => s.replace(/\r\n/g, '\n');
const fail = (m) => { throw new Error(m); };
const FLAGS = { '-h': 'help', '--help': 'help', '--dry-run': 'dryRun', '--force': 'force', '--backup': 'backup', '--json': 'json' };
const HDR_RE = /^# =+\n# AUTO-GENERATED by agy-ignore[\s\S]*?\n# =+\n+/;

export function parseArgs(argv) {
  const o = { workspaceDir: '.', source: DEFAULT_SOURCE, targets: [...DEFAULT_TARGETS] };
  for (const k of Object.values(FLAGS)) o[k] = false;
  let pos = false;
  for (let i = 0; i < argv.length; i++) {
    const a = argv[i], eq = a.indexOf('='), f = eq < 0 ? a : a.slice(0, eq);
    const val = () => {
      const v = eq < 0 ? argv[++i] : a.slice(eq + 1);
      return v && (eq >= 0 || !v.startsWith('-')) ? v : fail(`Missing ${f}`);
    };
    if (Object.hasOwn(FLAGS, a)) o[FLAGS[a]] = true;
    else if (f === '--source') o.source = val();
    else if (f === '--targets') {
      const seen = new Set();
      o.targets = val().split(',').map((t) => t.trim()).filter((t) => t && !seen.has(keyOf(t)) && seen.add(keyOf(t)));
      if (!o.targets.length) fail('Empty --targets');
    } else if (a.startsWith('-')) fail(`Unknown: ${a}`);
    else if (pos) fail(`Extra: ${a}`);
    else { o.workspaceDir = a; pos = true; }
  }
  return o;
}

export const getUsageText = () =>
  'Usage: sync_ignores.mjs [dir] [--source f] [--targets csv] [--dry-run|--backup|--force|--json|-h]';

export function buildSyncedContent(raw, src = DEFAULT_SOURCE) {
  const bar = `# ${'='.repeat(78)}`;
  const body = lf(raw).replace(/^\uFEFF/, '').replace(HDR_RE, '');
  return `${bar}\n# AUTO-GENERATED by agy-ignore (sync_ignores.mjs)\n# Source: ${src}\n# Do not edit this file manually; edit ${src} and re-run sync.\n${bar}\n\n${body}${body.endsWith('\n') ? '' : '\n'}`;
}

const stat = (p, fn = fs.lstatSync) => {
  try { return fn(p); } catch (e) { if (e.code === 'ENOENT') return null; throw e; }
};

function safePath(root, name) {
  if (!name || name.includes('\0')) fail(`Bad path: ${name}`);
  const abs = path.resolve(root, name), rel = path.relative(root, abs);
  if (!rel || /^\.\.($|[\\/])/.test(rel) || path.isAbsolute(rel)) fail(`Escapes: ${name}`);
  let cur = root;
  for (const p of rel.split(path.sep).slice(0, -1)) {
    const st = stat((cur = path.join(cur, p)));
    if (!st) break;
    if (st.isSymbolicLink() || !st.isDirectory()) fail(`Bad parent: ${cur}`);
  }
  return abs;
}

function nextBackup(abs) {
  let p = `${abs}.bak`;
  if (!stat(p)) return p;
  const pre = `${p}.${new Date().toISOString().replace(/[:.]/g, '-')}`;
  for (let n = 0; stat(p); n++) p = n ? `${pre}-${n}` : pre;
  return p;
}

export function syncIgnores(dir = '.', { source = DEFAULT_SOURCE, targets = DEFAULT_TARGETS, force, backup, dryRun } = {}) {
  const root = path.resolve(dir), dry = !!dryRun;
  if (!stat(root, fs.statSync)?.isDirectory()) fail(`Not a dir: ${root}`);
  const src = safePath(root, source);
  if (!stat(src, fs.statSync)?.isFile()) fail(`Not a regular file: ${src}`);

  const out = buildSyncedContent(fs.readFileSync(src, 'utf8'), source), seen = new Set(), results = [];
  let hasConflicts = false;

  for (const target of targets) {
    const abs = safePath(root, target), key = keyOf(abs);
    if (seen.has(key)) continue;
    seen.add(key);

    const add = (action, written = false, backupPath = null, message) =>
      results.push({ target, targetPath: abs, action, written, backupPath, ...(message && { message }) });
    const save = (d, r, bak = null) => {
      if (!dry) {
        if (bak) fs.copyFileSync(abs, bak);
        fs.mkdirSync(path.dirname(abs), { recursive: true });
        fs.writeFileSync(abs, out, 'utf8');
      }
      add(dry ? `would_${d}` : r, !dry, bak);
    };

    if (key === keyOf(src)) { add('skipped_same_as_source'); continue; }
    const st = stat(abs);
    if (st?.isSymbolicLink() || (st && !st.isFile())) fail(`Symlink/not a regular file: ${abs}`);
    if (!st) save('create', 'created');
    else if (lf(fs.readFileSync(abs, 'utf8')) === out) add('unchanged');
    else if (backup) save('backup_and_update', 'backed_up_and_updated', nextBackup(abs));
    else if (force) save('overwrite', 'overwritten');
    else { hasConflicts = true; add(dry ? 'would_skip_conflict' : 'skipped_conflict', false, null, 'Use --backup/--force'); }
  }
  return { workspaceRoot: root, sourcePath: src, dryRun: dry, hasConflicts, results };
}

function realUrl(p) {
  try { p = fs.realpathSync(p); } catch {}
  return keyOf(pathToFileURL(path.resolve(p)).href);
}

if (process.argv[1] && realUrl(fileURLToPath(import.meta.url)) === realUrl(process.argv[1])) {
  try {
    const o = parseArgs(process.argv.slice(2));
    if (o.help) console.log(getUsageText());
    else {
      const r = syncIgnores(o.workspaceDir, o);
      const fmt = (x) => `  - ${x.target}: ${x.action}${x.backupPath ? ` (backup: ${path.basename(x.backupPath)})` : ''}${x.message ? ` — ${x.message}` : ''}`;
      console.log(o.json ? JSON.stringify(r, null, 2) : `Sync: ${r.sourcePath}\n${r.results.map(fmt).join('\n')}`);
      if (r.hasConflicts && !r.dryRun) process.exitCode = 1;
    }
  } catch (e) {
    console.error(`Error: ${e.message}`);
    process.exitCode = 1;
  }
}
